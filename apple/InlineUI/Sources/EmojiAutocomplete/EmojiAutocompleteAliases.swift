  /// Fixes duplicate or mangled shortcodes in the generated data.
  static func shortcodeOverride(emoji: String, shortcode: String, label: String) -> String {
    switch shortcode {
    case "keycap":
      return keycapShortcode(label: label) ?? shortcode
    case "sunglasses" where emoji.unicodeScalars.first?.value == 0x1F576:
      return "dark_sunglasses"
    default:
      break
    }

    // CLDR labels with accented letters lost them in the generated shortcodes
    // ("pi_ata", "flag_t_rkiye"); rebuild those from the label instead.
    let hasAccentedLetter = label.unicodeScalars.contains { scalar in
      !scalar.isASCII && scalar.properties.isAlphabetic
    }
    guard hasAccentedLetter else { return shortcode }
    let rebuilt = EmojiAutocomplete.normalize(label)
    return rebuilt.isEmpty ? shortcode : rebuilt
  }

  private static func keycapShortcode(label: String) -> String? {
    guard let symbol = label.split(separator: ":").last?.trimmingCharacters(in: .whitespaces) else { return nil }
    switch symbol {
    case "#": return "hash"
    case "*": return "asterisk"
    default: return nil
    }
  }
}

