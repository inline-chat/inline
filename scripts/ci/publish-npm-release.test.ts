import { afterEach, beforeEach, describe, expect, it } from "bun:test"
import { createHash } from "node:crypto"
import { chmod, mkdir, mkdtemp, readFile, rm, symlink, writeFile } from "node:fs/promises"
import os from "node:os"
import path from "node:path"
import { pathToFileURL } from "node:url"
import { compareVersions, createGitHub, createRegistry, publishNpmRelease, runPublisher } from "./publish-npm-release.mjs"

type Published = { name: string; version: string; dist: { integrity: string; tarball: string } }
type Release = { tag_name: string; target_commitish: string; prerelease: boolean; draft: boolean }
type Payload = Record<string, unknown>
const sha = "a".repeat(40)
const origin = "https://registry.invalid"
const bytes = Buffer.from("exact retained tarball fixture")
const integrity = `sha512-${createHash("sha512").update(bytes).digest("base64")}`
const sha256 = createHash("sha256").update(bytes).digest("hex")
const helper = pathToFileURL(path.resolve(import.meta.dir, "publish-npm-release.mjs")).href

describe("retained npm publication", () => {
  let directory: string
  let version: string
  let tag: string
  let published: Published | null
  let downloaded: Buffer | null
  let tags: Record<string, string>
  let saved: Release | null
  let priorReleases: Record<string, Release>
  let refs: { ref: string }[]
  let commands: string[][]
  let ghCalls: { method: string; endpoint: string; payload?: Payload }[]
  let pauses: number[]
  let lostPublish: boolean
  let rejectPublish: boolean
  let visibilityDelay: number
  let failNotes: boolean
  let lostNotes: boolean
  let lostDistTag: boolean
  let rejectDistTag: boolean

  const metadata = (): Published => ({ name: "@inline-chat/protocol", version, dist: { integrity, tarball: `${origin}/fixture.tgz` } })
  const identity = (): Release => ({ tag_name: tag, target_commitish: sha, prerelease: version.includes("-"), draft: false })
  const receipt = () => ({ name: "@inline-chat/protocol", version, tag, sha, file: "fixture.tgz", integrity, sha256 })
  const writeReceipt = (overrides: Payload = {}) => writeFile(path.join(directory, "release-artifact.json"), JSON.stringify({ ...receipt(), ...overrides }))
  const registry = {
    version: async (_name: string, _version: string): Promise<Published | null> => {
      if (visibilityDelay > 0) { visibilityDelay--; return null }
      return published
    },
    tags: async (_name: string) => tags,
    tarball: async (_url: string) => downloaded,
  }
  const github = async (method: string, endpoint: string, payload?: Payload): Promise<unknown> => {
    ghCalls.push({ method, endpoint, payload })
    if (endpoint.startsWith("git/ref/tags/")) return { object: { type: "commit", sha } }
    if (endpoint.startsWith("releases/tags/")) {
      const requested = decodeURIComponent(endpoint.slice("releases/tags/".length))
      return requested === tag ? saved : priorReleases[requested] ?? null
    }
    if (endpoint.startsWith("git/matching-refs/")) return refs
    if (endpoint === "releases/generate-notes") {
      if (failNotes) throw new Error("automatic notes temporarily unavailable")
      return { name: "Automatic notes", body: "Generated by GitHub" }
    }
    if (method === "POST" && endpoint === "releases") {
      saved = identity()
      if (lostNotes) throw new Error("release creation response lost")
      return saved
    }
    throw new Error(`Unexpected GitHub operation: ${method} ${endpoint}`)
  }
  const npm = async (args: string[]) => {
    commands.push(args)
    if (args[0] === "publish" && !rejectPublish) {
      published = metadata()
      tags[args[args.indexOf("--tag") + 1]!] = version
      if (lostPublish) throw new Error("publish response lost")
    } else if (args[0] === "dist-tag" && !rejectDistTag) {
      tags[args[3]!] = version
      if (lostDistTag) throw new Error("dist-tag response lost")
    }
    return { status: rejectPublish || rejectDistTag ? 1 : 0, stdout: "" }
  }
  const options = () => ({ tag, sha, repository: "inline-chat/inline", registry, github, npm, pause: async (ms: number) => { pauses.push(ms) } })
  const run = () => publishNpmRelease(directory, options())
  const outcome = () => runPublisher([directory], options(), path.join(directory, "outputs"))

  beforeEach(async () => {
    directory = await mkdtemp(path.join(os.tmpdir(), "inline-publisher-test-"))
    version = "1.2.3-alpha.2"
    tag = `protocol-v${version}`
    published = null; downloaded = bytes; tags = { alpha: "1.2.3-alpha.1" }; saved = null
    priorReleases = Object.fromEntries(["protocol-v1.2.3-alpha.1", "protocol-v1.2.2"].map((prior) => [prior, { ...identity(), tag_name: prior }]))
    refs = [{ ref: "refs/tags/protocol-v1.2.3-alpha.1" }, { ref: "refs/tags/bot-client-v9.0.0" },
      { ref: "refs/tags/protocol-v1.2.3-alpha.3" }, { ref: "refs/tags/protocol-v1.2.2" }]
    commands = []; ghCalls = []; pauses = []
    lostPublish = false; rejectPublish = false; visibilityDelay = 0; failNotes = false
    lostNotes = false; lostDistTag = false; rejectDistTag = false
    await writeFile(path.join(directory, "fixture.tgz"), bytes)
    await writeReceipt()
  })
  afterEach(async () => { await rm(directory, { recursive: true, force: true }) })

  it("publishes the exact retained tarball and automatic notes from the previous package tag", async () => {
    expect((await run()).outcome).toBe("published")
    expect(commands).toEqual([["publish", path.join(directory, "fixture.tgz"), "--ignore-scripts", "--access", "public", "--tag", "alpha"]])
    expect(ghCalls.find((call) => call.endpoint === "releases/generate-notes")?.payload).toEqual({
      tag_name: tag, target_commitish: sha, previous_tag_name: "protocol-v1.2.3-alpha.1",
    })
    expect(ghCalls.find((call) => call.endpoint === "releases")?.payload).toEqual({
      tag_name: tag, target_commitish: sha, name: "Automatic notes", body: "Generated by GitHub", prerelease: true, draft: false, make_latest: "false",
    })
    expect(tags.alpha).toBe(version)
  })

  it("keeps stable publication on latest without marking npm as the GitHub latest release", async () => {
    version = "1.2.3"; tag = `protocol-v${version}`; tags = { latest: "1.2.2" }
    await writeReceipt()
    await run()
    expect(commands[0]?.at(-1)).toBe("latest")
    expect(ghCalls.find((call) => call.endpoint === "releases")?.payload).toMatchObject({ prerelease: false, make_latest: "false" })
  })

  it("skips failed release tags and drafts when choosing the previous package release", async () => {
    delete priorReleases["protocol-v1.2.3-alpha.1"]
    refs.push({ ref: "refs/tags/protocol-v1.2.3-alpha.0" })
    priorReleases["protocol-v1.2.3-alpha.0"] = { ...identity(), tag_name: "protocol-v1.2.3-alpha.0", draft: true }
    await run()
    expect(ghCalls.find((call) => call.endpoint === "releases/generate-notes")?.payload).toMatchObject({ previous_tag_name: "protocol-v1.2.2" })
    expect(ghCalls.some((call) => call.endpoint === "releases/tags/protocol-v1.2.3-alpha.1")).toBe(true)
    expect(ghCalls.some((call) => call.endpoint === "releases/tags/protocol-v1.2.3-alpha.0")).toBe(true)
    expect(ghCalls.find((call) => call.endpoint === "releases")?.payload?.body).toBe("Generated by GitHub")
  })

  it("labels initial package notes with the source commit without creating a baseline tag", async () => {
    priorReleases = {}
    await run()
    expect(ghCalls.find((call) => call.endpoint === "releases/generate-notes")?.payload).toEqual({ tag_name: tag, target_commitish: sha })
    expect(ghCalls.find((call) => call.endpoint === "releases")?.payload?.body).toBe(
      `Initial @inline-chat/protocol release tag. Source [${sha}](https://github.com/inline-chat/inline/commit/${sha}).\n\nGenerated by GitHub`)
    expect(ghCalls.filter((call) => call.method === "POST").map((call) => call.endpoint)).toEqual(["releases/generate-notes", "releases"])
  })

  it("skips every mutation when the bytes, channel, and GitHub release already agree", async () => {
    published = metadata(); tags.alpha = version; saved = identity()
    expect((await run()).outcome).toBe("already-current")
    expect(commands).toEqual([])
    expect(ghCalls.filter((call) => call.method !== "GET")).toEqual([])
  })

  it("finishes a missing dist-tag and notes without uploading an existing version", async () => {
    published = metadata(); lostDistTag = true
    expect((await run()).outcome).toBe("published")
    expect(commands).toEqual([["dist-tag", "add", `@inline-chat/protocol@${version}`, "alpha"]])
    expect(saved).toEqual(identity())
  })

  it("recovers a lost publish response by verifying bytes without a second upload", async () => {
    lostPublish = true
    expect((await run()).outcome).toBe("published")
    expect(commands.filter((args) => args[0] === "publish")).toHaveLength(1)
    expect(saved).toEqual(identity())
  })

  it("allows asynchronous registry processing after a lost response without a duplicate publication", async () => {
    const slowRegistry = { ...registry, version: async () => {
      if (published && visibilityDelay-- > 0) return null
      return published
    } }
    visibilityDelay = 29; lostPublish = true
    expect((await publishNpmRelease(directory, { ...options(), registry: slowRegistry })).outcome).toBe("published")
    expect(pauses).toEqual(Array(29).fill(5_000))
    expect(commands.filter((args) => args[0] === "publish")).toHaveLength(1)
  })

  it("fails a rejected upload after bounded polling and records the terminal outcome", async () => {
    rejectPublish = true
    expect((await outcome()).outcome).toBe("failed")
    expect(pauses).toEqual(Array(29).fill(5_000))
    expect(commands).toHaveLength(1)
    expect(saved).toBeNull()
    expect(await readFile(path.join(directory, "outputs"), "utf8")).toContain("outcome=failed\nreason=npm publish failed;")
  })

  it("blocks different published bytes even when the registry claims the retained integrity", async () => {
    published = metadata(); downloaded = Buffer.from("different published artifact")
    expect((await outcome()).outcome).toBe("blocked")
    expect(await readFile(path.join(directory, "outputs"), "utf8")).toContain("Published tarball bytes differ")
    expect(commands).toEqual([])
    expect(saved).toBeNull()
  })

  it("blocks changed registry version identity or integrity before modifying a channel", async () => {
    for (const changed of [{ ...metadata(), name: "@attacker/wrong" }, { ...metadata(), version: "9.0.0" },
      { ...metadata(), dist: { ...metadata().dist, integrity: "sha512-forged" } }]) {
      published = changed
      expect((await outcome()).outcome).toBe("blocked")
    }
    expect(commands).toEqual([])
  })

  it("never treats a missing existing tarball as permission to republish the version", async () => {
    published = metadata(); downloaded = null
    expect((await outcome()).outcome).toBe("failed")
    expect(commands).toEqual([])
    expect(pauses).toHaveLength(29)
  })

  it("rejects receipt identity, path, and digest changes before any provider operation", async () => {
    for (const changed of [{ name: "@attacker/wrong" }, { version: "9.0.0" }, { tag: "protocol-v9.0.0" },
      { sha: "b".repeat(40) }, { file: "../fixture.tgz" }, { sha256: "0".repeat(64) }, { integrity: "sha512-forged" }]) {
      await writeReceipt(changed)
      expect((await outcome()).outcome).toBe("blocked")
    }
    expect(commands).toEqual([])
    expect(ghCalls).toEqual([])
  })

  it("rejects receipt and tarball symlinks", async () => {
    const receiptPath = path.join(directory, "release-artifact.json")
    await writeFile(path.join(directory, "other.json"), JSON.stringify(receipt()))
    await rm(receiptPath)
    await symlink(path.join(directory, "other.json"), receiptPath)
    expect((await outcome()).outcome).toBe("blocked")
    await rm(receiptPath); await writeReceipt()
    await writeFile(path.join(directory, "other.tgz"), bytes)
    await rm(path.join(directory, "fixture.tgz"))
    await symlink(path.join(directory, "other.tgz"), path.join(directory, "fixture.tgz"))
    expect((await outcome()).outcome).toBe("blocked")
    expect(ghCalls).toEqual([])
  })

  it("blocks a new version older than its channel before uploading", async () => {
    tags.alpha = "1.2.3-alpha.10"
    expect((await outcome()).outcome).toBe("blocked")
    expect(commands).toEqual([])
    expect(saved).toBeNull()
  })

  it("leaves a newer channel alone when resuming an already published older version", async () => {
    published = metadata(); tags.alpha = "1.2.3-alpha.10"
    const result = await run()
    expect(result.reason).toContain("alpha=1.2.3-alpha.10")
    expect(commands).toEqual([])
    expect(saved).toEqual(identity())
  })

  it("fails channel convergence without weakening or skipping the operation", async () => {
    published = metadata(); rejectDistTag = true
    expect((await outcome()).outcome).toBe("failed")
    expect(commands).toHaveLength(1)
    expect(pauses).toHaveLength(29)
    expect(saved).toBeNull()
  })

  it("resumes partial notes failure without republishing the accepted tarball", async () => {
    failNotes = true
    expect((await outcome()).outcome).toBe("failed")
    expect(published).toEqual(metadata())
    failNotes = false
    expect((await outcome()).outcome).toBe("published")
    expect(commands.filter((args) => args[0] === "publish")).toHaveLength(1)
    expect(saved).toEqual(identity())
  })

  it("recovers a lost GitHub creation response by checking the saved identity", async () => {
    lostNotes = true
    expect((await run()).outcome).toBe("published")
    expect(ghCalls.filter((call) => call.endpoint === "releases")).toHaveLength(1)
  })

  it("refuses an existing GitHub release with different source, tag, prerelease, or draft identity", async () => {
    for (const changed of [{ target_commitish: "main" }, { tag_name: "protocol-v9.0.0" }, { prerelease: false }, { draft: true }]) {
      saved = { ...identity(), ...changed }
      expect((await outcome()).outcome).toBe("blocked")
    }
    expect(commands).toEqual([])
    expect(ghCalls.filter((call) => call.method !== "GET")).toEqual([])
  })

  it("verifies peeled annotated tags and blocks a different commit", async () => {
    const annotated = async (method: string, endpoint: string, payload?: Payload) => {
      if (endpoint.startsWith("git/ref/tags/")) return { object: { type: "tag", sha: "b".repeat(40) } }
      if (endpoint.startsWith("git/tags/")) return { object: { type: "commit", sha } }
      return github(method, endpoint, payload)
    }
    expect((await publishNpmRelease(directory, { ...options(), github: annotated })).outcome).toBe("published")
    const wrong = async () => ({ object: { type: "commit", sha: "b".repeat(40) } })
    await expect(publishNpmRelease(directory, { ...options(), github: wrong })).rejects.toThrow("does not identify the release commit")
  })

  it("runs the native Node publisher with isolated OIDC-only npm config and no lifecycle or installation", async () => {
    const bin = path.join(directory, "bin"), state = path.join(directory, "state")
    await mkdir(bin)
    await writeFile(path.join(bin, "npm"), String.raw`#!/usr/bin/env node
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path')
const args = process.argv.slice(2)
assert.equal(args[0], 'publish')
for (const key of Object.keys(process.env)) assert(!/^npm_config_/i.test(key) && !/^(?:npm_token|node_auth_token)$/i.test(key))
assert(process.env.ACTIONS_ID_TOKEN_REQUEST_URL)
assert(process.env.ACTIONS_ID_TOKEN_REQUEST_TOKEN)
assert.equal(fs.readdirSync(process.cwd()).length, 0)
for (const flag of ['--ignore-scripts', '--registry=https://registry.npmjs.org']) assert(args.includes(flag))
for (const name of ['user', 'global']) {
  const config = args.find(arg => arg.startsWith('--' + name + 'config=')).split('=').slice(1).join('=')
  assert.equal(fs.realpathSync(path.dirname(config)), fs.realpathSync(process.cwd()))
  assert.equal(path.basename(config), name + '.npmrc')
}
assert.equal(fs.readFileSync(args[1], 'utf8'), 'exact retained tarball fixture')
fs.writeFileSync(process.env.PUBLISH_TEST_STATE, JSON.stringify(args))
`)
    await chmod(path.join(bin, "npm"), 0o700)
    const script = `import { publishNpmRelease } from ${JSON.stringify(helper)};
      import { existsSync } from 'node:fs';
      const metadata = ${JSON.stringify(metadata())}, identity = ${JSON.stringify(identity())};
      const result = await publishNpmRelease(${JSON.stringify(directory)}, {tag:${JSON.stringify(tag)},sha:${JSON.stringify(sha)},
        registry:{version:async()=>existsSync(${JSON.stringify(state)})?metadata:null,tags:async()=>existsSync(${JSON.stringify(state)})?{alpha:metadata.version}:{},tarball:async()=>Buffer.from('exact retained tarball fixture')},
        pause:async()=>{},github:async(method,endpoint)=>endpoint.startsWith('git/ref/')?{object:{type:'commit',sha:identity.target_commitish}}:identity});
      if(result.outcome!=='published')throw new Error('unexpected outcome');`
    const result = Bun.spawnSync(["node", "--input-type=module", "--eval", script], { env: { ...process.env,
      PATH: `${bin}:${process.env.PATH}`, PUBLISH_TEST_STATE: state, NODE_AUTH_TOKEN: "synthetic-never-use", NPM_TOKEN: "synthetic-never-use",
      NPM_CONFIG_USERCONFIG: "/synthetic/never-read", ACTIONS_ID_TOKEN_REQUEST_URL: "https://oidc.invalid", ACTIONS_ID_TOKEN_REQUEST_TOKEN: "synthetic-oidc",
    } })
    expect(result.exitCode, result.stderr.toString()).toBe(0)
    expect(JSON.parse(await readFile(state, "utf8"))[0]).toBe("publish")
  })
})

describe("publication transports and version ordering", () => {
  it("orders canonical prereleases without number precision loss", () => {
    const ordered = ["1.0.0-alpha", "1.0.0-alpha.1", "1.0.0-alpha.2", "1.0.0-alpha.10", "1.0.0-beta", "1.0.0", "1.0.1", "9007199254740993.0.0"]
    for (let i = 1; i < ordered.length; i++) expect(compareVersions(ordered[i - 1]!, ordered[i]!)).toBe(-1)
    expect(compareVersions("1.0.0", "1.0.0")).toBe(0)
    expect(compareVersions("1.0.0-alpha.2", "1.0.0-alpha.1")).toBe(1)
    for (const invalid of ["v1.0.0", "1.0.0+build", "1.0.0-alpha.01"]) expect(() => compareVersions(invalid, "1.0.0")).toThrow()
  })

  it("uses a reserved injected registry, verifies actual tarball bytes, and rejects foreign origins", async () => {
    const calls: { url: string; init?: RequestInit }[] = []
    const transport = async (url: string, init?: RequestInit) => {
      calls.push({ url, init })
      return url.endsWith(".tgz") ? new Response(bytes) : Response.json({ name: "@inline-chat/protocol" })
    }
    const registry = createRegistry(transport, origin)
    await registry.version("@inline-chat/protocol", "1.0.0")
    expect(await registry.tarball(`${origin}/fixture.tgz`)).toEqual(bytes)
    expect(calls.map((call) => call.url)).toEqual([`${origin}/%40inline-chat%2Fprotocol/1.0.0`, `${origin}/fixture.tgz`])
    expect(calls.every((call) => call.init?.redirect === "error" && call.init.signal instanceof AbortSignal)).toBe(true)
    for (const url of ["https://foreign.invalid/fixture.tgz", "http://registry.invalid/fixture.tgz", "https://synthetic:password@registry.invalid/fixture.tgz"]) {
      await expect(registry.tarball(url)).rejects.toThrow("Unexpected npm tarball origin")
    }
    expect(calls).toHaveLength(2)
  })

  it("treats only actual registry HTTP 404 as missing; network/auth/server failures fail closed", async () => {
    const missing = createRegistry(async () => new Response("not found", { status: 404 }), origin)
    expect(await missing.version("fixture", "1.0.0")).toBeNull()
    expect(await missing.tags("fixture")).toEqual({})
    for (const status of [401, 403, 429, 500]) {
      const failing = createRegistry(async () => new Response('{"error":"E404"}', { status }), origin)
      await expect(failing.version("fixture", "1.0.0")).rejects.toThrow(`HTTP ${status}`)
    }
    const network = createRegistry(async () => { throw new Error("connection reset") }, origin)
    await expect(network.version("fixture", "1.0.0")).rejects.toThrow("connection reset")
  })

  it("uses GitHub API payload stdin and checks HTTP status rather than error text", async () => {
    const calls: { program: string; args: string[]; input?: string }[] = []
    let status = 200
    const api = createGitHub("inline-chat/inline", (program: string, args: string[], input?: string) => {
      calls.push({ program, args, input })
      return { status: status === 200 ? 0 : 1, stdout: `HTTP/2.0 ${status} Response\r\ncontent-type: application/json\r\n\r\n{"name":"E404"}` }
    })
    expect(await api("POST", "releases/generate-notes", { tag_name: "protocol-v1.0.0" })).toEqual({ name: "E404" })
    expect(calls[0]).toEqual({ program: "gh", args: ["api", "--hostname", "github.com", "--include", "--method", "POST", "repos/inline-chat/inline/releases/generate-notes", "--input", "-"], input: '{"tag_name":"protocol-v1.0.0"}' })
    status = 404; expect(await api("GET", "releases/tags/missing")).toBeNull()
    status = 401; await expect(api("GET", "releases/tags/missing")).rejects.toThrow("HTTP 401")
    const network = createGitHub("inline-chat/inline", () => ({ status: 1, stdout: "connection failed (E404)" }))
    await expect(network("GET", "releases/tags/missing")).rejects.toThrow("did not return an HTTP response")
  })
})
