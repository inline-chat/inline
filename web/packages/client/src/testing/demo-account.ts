/**
 * The demo account: a realistic account at any scale whose messages are
 * computed on demand, so a server model can hold hundreds of thousands of
 * them without generating or storing them up front.
 *
 * - Structure (users with names in several scripts, spaces, chat titles,
 *   participants) comes from `generateSeedAccount` run with no messages.
 * - Message texts come from a small corpus generated by `generateSeedAccount`
 *   (Latin, Arabic, Hebrew, CJK, Cyrillic, mixed scripts and emoji, mentions,
 *   URLs, multi-paragraph texts), grouped by the chat they were written for
 *   so a chat keeps one "voice". A chat takes a voice in its title's script.
 * - Every seeded message is a pure function of (seed, chat, message ID):
 *   `messageAt` can produce message 17,000 of the busiest chat without
 *   producing the 16,999 before it.
 *
 * Message counts follow the same long tail as `SEED_ACCOUNT_SCALES`; a share
 * of chats has an unread tail, a few are pinned, some archived, and the
 * inbox holds the recently active ones.
 *
 * People and content (`demo-people.ts`, `demo-content.ts`): users have first
 * and last names in several scripts, usernames and some generated avatars;
 * about 40% of the chats outside spaces are direct messages; space threads
 * are public or private (a subset of the space); one space thread in seven
 * has the agent posting blocks, buttons and forms; messages carry media,
 * entities, forwards and edits, and about 1.5% of seeded IDs are holes
 * (deleted long ago). Chat counts per scale are unchanged.
 */

export type DemoScale = keyof typeof SEED_ACCOUNT_SCALES

export const DEMO_SCALES: Record<DemoScale, { chats: number; messages: number }> = SEED_ACCOUNT_SCALES

export const isDemoScale = (value: unknown): value is DemoScale =>
  value === "small" || value === "medium" || value === "large"

export type DemoChatPlan = {
  id: bigint
  title: string
  spaceId?: bigint
  /** Every member, the account's user included. */
  participants: bigint[]
  /** Members other than the account's user; never empty. */
  others: bigint[]
  /** Seeded messages have IDs 1 through `count`. */
  count: number
  /** Date of message `count`, in seconds. */
  lastDate: number
  /** Average seconds between seeded messages. */
  gap: number
  readMaxId: bigint
  pinned: boolean
  pinnedOrder?: string
  archived: boolean
  open: boolean
  order?: string
  /** Index into `DemoAccount.voices`. */
  voice: number
  /** A direct message with this user (no space, no title). */
  peerUserId?: bigint
  /** A space thread every member of the space can see. */
  isPublic?: boolean
  /** The agent is a member and posts rich content here. */
  agent?: boolean
}

export type DemoAccountOptions = {
  seed: number
  scale: DemoScale
  /** Seconds. Seeded dates end at or before it. */
  anchor: number
  selfUserId?: bigint
}

export type DemoAccount = {
  readonly seed: number
  readonly scale: DemoScale
  readonly anchor: number
  readonly selfUserId: bigint
  /** A bot-like user that streams long answers (`DemoWorld` agent). */
  readonly agentUserId: bigint
  readonly users: ReadonlyArray<DemoUser>
  readonly spaces: ReadonlyArray<DemoSpace>
  /** Ordered by ID. */
  readonly chats: readonly DemoChatPlan[]
  readonly totalMessages: number
  readonly voices: readonly (readonly string[])[]
  messageAt(chat: DemoChatPlan, id: bigint): DemoModelMessage
  /** A seeded ID deleted long ago: never served. */
  holeAt(chat: DemoChatPlan, id: bigint): boolean
  authorAt(chat: DemoChatPlan, id: bigint): bigint
  user(id: bigint): DemoUser | undefined
  /** A text in the chat's voice, for live messages. */
  textFor(chat: DemoChatPlan, random: SeededRandom): string
}

type Script = "latin" | "arabic" | "hebrew" | "cjk" | "cyrillic" | "mixed"

const scriptOf = (text: string): Script => {
  const counts = { latin: 0, arabic: 0, hebrew: 0, cjk: 0, cyrillic: 0 }
  for (const char of text) {
    const code = char.codePointAt(0) ?? 0
    if (code >= 0x0600 && code <= 0x06ff) counts.arabic += 1
    else if (code >= 0x0590 && code <= 0x05ff) counts.hebrew += 1
    else if ((code >= 0x3040 && code <= 0x30ff) || (code >= 0x4e00 && code <= 0x9fff)) counts.cjk += 1
    else if (code >= 0x0400 && code <= 0x04ff) counts.cyrillic += 1
    else if ((code >= 0x41 && code <= 0x5a) || (code >= 0x61 && code <= 0x7a) || (code >= 0xc0 && code <= 0x24f)) {
      counts.latin += 1
    }
  }
  const total = counts.latin + counts.arabic + counts.hebrew + counts.cjk + counts.cyrillic
  if (total === 0) return "latin"
  let best: Exclude<Script, "mixed"> = "latin"
  for (const key of ["arabic", "hebrew", "cjk", "cyrillic"] as const) {
    if (counts[key] > counts[best]) best = key
  }
  return counts[best] / total >= 0.7 ? best : "mixed"
}

/** A 32-bit seed from three integers. */
const mix = (a: number, b: number, c: number) => {
  let hash = (a ^ 0x9e3779b9) >>> 0
  hash = Math.imul(hash ^ (b >>> 0), 0x85ebca6b) >>> 0
  hash = Math.imul(hash ^ (hash >>> 13) ^ (c >>> 0), 0xc2b2ae35) >>> 0
  hash = Math.imul(hash ^ Math.floor(c / 0x1_0000_0000), 0x27d4eb2f) >>> 0
  return (hash ^ (hash >>> 16)) >>> 0
}

/** Long-tail weights: chat i gets roughly 1 / (i + 1)^0.9 of the messages. */
const distribute = (total: number, chats: number) => {
  const weights = Array.from({ length: chats }, (_, index) => 1 / Math.pow(index + 1, 0.9))
  const sum = weights.reduce((acc, weight) => acc + weight, 0)
  const counts = weights.map((weight) => Math.floor((total * weight) / sum))
  const assigned = counts.reduce((acc, count) => acc + count, 0)
  counts[0] = (counts[0] ?? 0) + (total - assigned)
  return counts
}

const CORPUS = { chats: 30, messages: 6_000 } as const
const reactionEmoji = ["👍", "🎉", "👀", "🔥", "✅", "🙏", "😂"]
const DAY = 24 * 60 * 60

export const AGENT_USER_ID = 9_000n

const SPACE_NAMES = ["Northwind", "Design Guild", "Platform", "Field Ops", "Research", "Studio", "Growth", "Atlas", "Harbor", "Orbit", "Summit", "Relay"]

/** A user's display name. */
export const demoDisplayName = demoUserName

export const createDemoAccount = (options: DemoAccountOptions): DemoAccount => {
  const { seed, scale, anchor } = options
  const selfUserId = options.selfUserId ?? 1n
  const size = DEMO_SCALES[scale]

  // Voices: corpus texts grouped by the chat they were written for.
  const byChat = new Map<bigint, string[]>()
  for (const record of generateSeedAccount({
    seed,
    ...CORPUS,
    users: 6,
    spaces: 1,
    threadShare: 0,
    selfUserId,
  })) {
    if (record.kind !== "message") continue
    const texts = byChat.get(record.message.chatId) ?? []
    texts.push(record.message.message ?? "")
    byChat.set(record.message.chatId, texts)
  }
  const voices = Array.from(byChat.values()).filter((texts) => texts.length >= 20)
  if (voices.length === 0) throw new Error("The demo corpus is empty")
  const voiceScripts = voices.map((texts) => scriptOf(texts.slice(0, 40).join(" ")))

  // Structure: users, spaces, chats with titles and members; no messages.
  const userIds: bigint[] = []
  const spaceShells: Array<{ id: bigint; name: string }> = []
  const shells: Array<{ id: bigint; title: string; spaceId?: bigint; participants: bigint[] }> = []
  for (const record of generateSeedAccount({ seed, chats: size.chats, messages: 0, selfUserId })) {
    switch (record.kind) {
      case "user":
        if (record.user.id !== selfUserId) userIds.push(record.user.id)
        break
      case "space":
        spaceShells.push({
          id: record.space.id,
          name: SPACE_NAMES[spaceShells.length] ?? record.space.name,
        })
        break
      case "chat":
        shells.push({
          id: record.chat.id,
          title: record.chat.title ?? `Chat ${record.chat.id}`,
          ...(record.chat.spaceId != null ? { spaceId: record.chat.spaceId } : {}),
          participants: record.participants,
        })
        break
      case "message":
        break
    }
  }
  const users: DemoUser[] = demoUsers(seed, userIds)
  users.push({ id: AGENT_USER_ID, firstName: "Agent", username: "agent", avatar: true, bot: true })
  const usersById = new Map(users.map((user) => [user.id, user]))

  const random = new SeededRandom(seed).fork("demo-plan")
  const counts = random.shuffle(distribute(size.messages, shells.length))
  const chats: DemoChatPlan[] = shells.map((shell, index) => {
    const count = counts[index] ?? 0
    const script = scriptOf(shell.title)
    const matching = voiceScripts.flatMap((voiceScript, voice) =>
      voiceScript === script ? [voice] : [],
    )
    const voice = matching.length > 0 ? random.pick(matching) : random.int(0, voices.length - 1)
    // Recency: most chats were active in the last weeks, a few today.
    const recency = random.bool(0.1)
      ? random.int(0, 6 * 60 * 60)
      : Math.floor(120 * DAY * Math.pow(random.next(), 2.5))
    const historySeconds = random.int(20, 700) * DAY
    const tail = count > 0 && random.bool(0.35) ? random.int(1, Math.min(40, count)) : 0
    const others = shell.participants.filter((id) => id !== selfUserId)
    return {
      id: shell.id,
      title: shell.title,
      ...(shell.spaceId != null ? { spaceId: shell.spaceId } : {}),
      participants: shell.participants,
      others: others.length > 0 ? others : [users[0]?.id ?? 2n],
      count,
      lastDate: anchor - recency,
      gap: Math.max(20, Math.floor(historySeconds / Math.max(1, count))),
      readMaxId: BigInt(count - tail),
      pinned: false,
      archived: false,
      open: false,
      voice,
    }
  })

  // People: direct messages among the chats outside spaces (one per person),
  // public and private space threads, the agent in some threads.
  const people = new SeededRandom(seed).fork("demo-people")
  const dmPeers = new Set<bigint>()
  for (const chat of chats) {
    if (chat.spaceId == null) {
      const peer = chat.others[0]
      if (peer != null && !dmPeers.has(peer) && people.bool(0.4)) {
        dmPeers.add(peer)
        chat.peerUserId = peer
        chat.title = ""
        chat.participants = [selfUserId, peer]
        chat.others = [peer]
      }
    } else {
      chat.isPublic = people.bool(0.55)
      if (people.bool(1 / 7)) {
        chat.agent = true
        chat.participants = [...chat.participants, AGENT_USER_ID]
      }
    }
  }
  const spaces = demoSpaces({ seed, selfUserId, anchor, spaces: spaceShells, chats, users })

  // Sidebar flags, by recency: a few pinned, some archived, the recent ones open.
  const byRecency = chats.slice().sort((left, right) => right.lastDate - left.lastDate)
  const inboxSize = Math.max(15, Math.ceil(chats.length * 0.4))
  let pinned = 0
  byRecency.forEach((chat, rank) => {
    if (rank < 12 && pinned < 4 && random.bool(0.35)) {
      chat.pinned = true
      chat.pinnedOrder = `p${pinned}`
      pinned += 1
    } else if (random.bool(0.08)) {
      chat.archived = true
    }
    if (!chat.archived && rank < inboxSize) {
      chat.open = true
      chat.order = `o${rank.toString(36).padStart(4, "0")}`
    }
  })

  const voiceOf = (chat: DemoChatPlan) => voices[chat.voice] ?? voices[0]!
  const streamFor = (chat: DemoChatPlan, id: bigint) =>
    new SeededRandom(mix(seed, Number(chat.id), Number(id)))
  const pickAuthor = (chat: DemoChatPlan, stream: SeededRandom) =>
    stream.bool(0.2) ? selfUserId : stream.pick(chat.others)

  const withContent = chats.filter((chat) => chat.count > 0)
  const mentionable = new Map<bigint, Array<{ id: bigint; name: string }>>()
  const mentionableIn = (chat: DemoChatPlan) => {
    let list = mentionable.get(chat.id)
    if (!list) {
      list = chat.participants.flatMap((id) => {
        const user = usersById.get(id)
        return id !== selfUserId && user ? [{ id, name: user.firstName }] : []
      })
      mentionable.set(chat.id, list)
    }
    return list
  }

  const messageAt = (chat: DemoChatPlan, id: bigint): DemoModelMessage => {
    const stream = streamFor(chat, id)
    const author = pickAuthor(chat, stream)
    const voiceText = stream.pick(voiceOf(chat))
    const position = Number(id)
    const replyToMsgId =
      position > 1 && stream.bool(0.08)
        ? BigInt(stream.int(Math.max(1, position - 40), position - 1))
        : undefined
    const jitter = position === chat.count ? 0 : stream.int(0, Math.floor(chat.gap / 2))
    const date = BigInt(chat.lastDate - (chat.count - position) * chat.gap - jitter)
    const reactions: ModelReaction[] = []
    if (stream.bool(0.06)) {
      for (let index = stream.int(1, 3); index > 0; index -= 1) {
        const userId = stream.pick(chat.participants)
        const emoji = stream.pick(reactionEmoji)
        if (!reactions.some((reaction) => reaction.userId === userId && reaction.emoji === emoji)) {
          reactions.push({ userId, emoji, date: date + BigInt(stream.int(1, 3_600)) })
        }
      }
    }
    const content = seededContent(
      {
        seed,
        chatId: chat.id,
        messageId: id,
        agent: chat.agent ? AGENT_USER_ID : undefined,
        mentionable: mentionableIn(chat),
        forwardSource: (random) => {
          const source = random.pick(withContent)
          if (source.id === chat.id) return undefined
          const messageId = BigInt(random.int(1, source.count))
          return { chatId: source.id, fromId: pickAuthor(source, streamFor(source, messageId)), messageId }
        },
      },
      { text: voiceText, fromId: author, date },
    )
    return {
      id,
      chatId: chat.id,
      fromId: content.fromId,
      text: content.text,
      date,
      ...(content.editDate != null ? { editDate: content.editDate } : {}),
      ...(replyToMsgId != null ? { replyToMsgId } : {}),
      reactions,
      ...(content.extras ? { extras: content.extras } : {}),
    }
  }

  return {
    seed,
    scale,
    anchor,
    selfUserId,
    agentUserId: AGENT_USER_ID,
    users,
    spaces,
    chats,
    totalMessages: counts.reduce((sum, count) => sum + count, 0),
    voices,
    messageAt,
    holeAt: (chat, id) => seededHole(seed, chat.id, id, chat.count),
    authorAt: (chat, id) => messageAt(chat, id).fromId,
    user: (id) => usersById.get(id),
    textFor: (chat, stream) => stream.pick(voiceOf(chat)),
  }
}
