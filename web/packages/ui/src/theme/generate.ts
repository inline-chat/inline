/**
 * Renders the StyleX source for the themes from `palette.ts`. StyleX needs
 * literal values at compile time, so the derived values are written into
 * checked-in files; `generate.test.ts` fails when they drift and rewrites
 * them with `UPDATE_THEMES=1 bunx vitest run src/theme/generate.test.ts`.
 */

import { THEME_IDS, THEME_TITLES, type ThemeId } from "./catalog"
import { themeValues, type TokenValue } from "./palette"

export const GENERATED_THEMES_PATH = "src/theme/themes.ts"
export const GENERATED_THEME_COLOR_PATH = "src/tokens/theme-color.stylex.ts"

const HEADER = "// Generated by src/theme/generate.ts from src/theme/catalog.ts and palette.ts. Do not edit."

/** `neon-noir` becomes `neonNoir`. */
export const themeExportName = (theme: ThemeId): string => theme.replace(/-(\w)/g, (_, c: string) => c.toUpperCase())

const renderValue = (value: TokenValue): string =>
  typeof value === "string"
    ? JSON.stringify(value)
    : `{ ${Object.entries(value)
        .map(([condition, v]) => `${condition === "default" ? "default" : JSON.stringify(condition)}: ${JSON.stringify(v)}`)
        .join(", ")} }`

const renderEntries = (values: Record<string, TokenValue>, indent: string) =>
  Object.entries(values)
    .map(([token, value]) => `${indent}${token}: ${renderValue(value)},`)
    .join("\n")

export function renderThemesModule(): string {
  const blocks = THEME_IDS.map((theme) => {
    const name = themeExportName(theme)
    const values = themeValues(theme)
    return [
      `/** ${THEME_TITLES[theme]} */`,
      `export const ${name}Color = stylex.createTheme(color, {`,
      renderEntries(values.color, "  "),
      `})`,
      `export const ${name}ThemeColor = stylex.createTheme(themeColor, {`,
      renderEntries(values.themeColor, "  "),
      `})`,
    ].join("\n")
  })
  return [
    HEADER,
    "",
    'import * as stylex from "@stylexjs/stylex"',
    'import { color } from "../tokens/color.stylex"',
    'import { themeColor } from "../tokens/theme-color.stylex"',
    "",
    blocks.join("\n\n"),
    "",
  ].join("\n")
}

export function renderThemeColorTokens(): string {
  const values = themeValues("system").themeColor
  return [
    HEADER,
    "",
    'import * as stylex from "@stylexjs/stylex"',
    "",
    "/**",
    " * Theme colors the kit had no token for, from apple/InlineMacUI MacTheme/Theme.swift:",
    " * the link color inside others' bubbles (`resolvedSecondaryBubbleLinkColor`) and the",
    " * reply thread pane (`replyThreadPaneBackgroundColor`). Defaults are the System theme;",
    " * every theme in src/theme/themes.ts overrides both.",
    " */",
    "export const themeColor = stylex.defineVars({",
    renderEntries(values, "  "),
    "})",
    "",
  ].join("\n")
}
