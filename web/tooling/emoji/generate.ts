/**
 * Emoji data for the web, generated from the Mac app's Swift sources.
 *
 *   bun tooling/emoji/generate.ts          write the modules (from web/)
 *   bun tooling/emoji/generate.ts --check  exit 1 when they are out of date
 *
 * Writes two modules into `web/src/features/emoji/data/`:
 *
 * - `emoji-data.generated.ts`: the searchable table, loaded on first use as
 *   its own chunk. One string, one row per base emoji (skin tone variants are
 *   folded into a tone field), tab-separated fields: emoji, shortcode, label,
 *   aliases, CLDR keywords, tone. Aliases and keywords are stored normalized
 *   and without the duplicates the Mac's index drops anyway, so the table is
 *   smaller and the runtime does not normalize them again; their order is
 *   kept because the Mac's word order decides multi-word ties.
 * - `quick-reactions.generated.ts`: the quick reaction set, its tone
 *   templates and the legacy acknowledgement marks. Tiny; the reaction row
 *   draws from it before the table loads.
 *
 * Skin tones: the Mac data lists every toned variant as its own row. A base
 * emoji supports tones when all five uniform-tone variants exist (the rows
 * whose usage key matches the base's and whose modifiers are all the same
 * tone). Mixed-tone variants (two people with different tones) are not
 * offered, as on the Mac. The tone field is `""` (none), `"1"` (the modifier
 * goes after the first code point, dropping a VS16 there) or the light
 * variant itself, whose U+1F3FB marks each place a tone goes. The generator
 * checks that every tone's variant is exactly what the field produces.
 *
 * Shortcode fixes: `EmojiAutocompleteAliases.shortcodeOverride`
 * (`EmojiAutocompleteAliases.swift` lines 289-317) is applied here.
 */

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { normalize } from "../../src/features/emoji/normalize"
import { containsSkinTone, insertModifier, SKIN_TONE_MODIFIERS, SKIN_TONES, usageKey } from "../../src/features/emoji/tone"
import {
  parseAliases,
  parseLegacyAcknowledgements,
  parsePopularity,
  parseQuickReactions,
  parseRawEntries,
  parseSectionBoundaries,
  readSwiftSources,
  SWIFT_SOURCES,
  type SwiftSources,
} from "./swift-sources"

const here = dirname(fileURLToPath(import.meta.url))
export const REPO_ROOT = join(here, "../../..")
export const OUTPUT_DIR = join(here, "../../src/features/emoji/data")
export const DATA_FILE = join(OUTPUT_DIR, "emoji-data.generated.ts")
export const QUICK_FILE = join(OUTPUT_DIR, "quick-reactions.generated.ts")

const LIGHT = SKIN_TONE_MODIFIERS.light
const toneModifierPattern = /[\u{1F3FB}-\u{1F3FF}]/gu

/** `EmojiAutocompleteAliases.shortcodeOverride` (lines 290-317). */
export const shortcodeOverride = (emoji: string, shortcode: string, label: string): string => {
  if (shortcode === "keycap") {
    const symbol = label.split(":").at(-1)?.trim()
    if (symbol === "#") return "hash"
    if (symbol === "*") return "asterisk"
    return shortcode
  }
  if (shortcode === "sunglasses" && emoji.codePointAt(0) === 0x1f576) return "dark_sunglasses"
  // CLDR labels with accented letters lost them in the generated shortcodes; rebuild those from the label.
  const hasAccentedLetter = Array.from(label).some((char) => (char.codePointAt(0) ?? 0) > 0x7f && /\p{Alphabetic}/u.test(char))
  if (!hasAccentedLetter) return shortcode
  const rebuilt = normalize(label)
  return rebuilt === "" ? shortcode : rebuilt
}

const isAscii = (value: string) => Array.from(value).every((char) => (char.codePointAt(0) ?? 0) < 0x80)

export type GeneratedModules = { readonly data: string; readonly quick: string; readonly stats: GeneratedStats }
export type GeneratedStats = { readonly rows: number; readonly baseRows: number; readonly toneable: number; readonly explicitTones: number }

const header = (sources: readonly string[]) =>
  [
    "// Generated by web/tooling/emoji/generate.ts. Do not edit; run `bun tooling/emoji/generate.ts` from web/.",
    `// Sources: ${sources.join(", ")}.`,
    "// Unicode Emoji 15.1 and CLDR 44 data, used under the Unicode License v3; see LICENSE-UNICODE at the repository root.",
    "",
  ].join("\n")

export const generateEmojiModules = (sources: SwiftSources = readSwiftSources(REPO_ROOT)): GeneratedModules => {
  const raw = parseRawEntries(sources.data)
  const aliases = parseAliases(sources.aliases)
  const popularity = parsePopularity(sources.aliases)
  const boundaries = parseSectionBoundaries(sources.pickerData)
  const quick = parseQuickReactions(sources.reactions)
  const legacy = parseLegacyAcknowledgements(sources.reactions)

  const rows = raw.map((row) => ({ ...row, shortcode: shortcodeOverride(row.emoji, row.shortcode, row.label) }))

  // Uniform-tone variants by usage key and tone.
  const variants = new Map<string, Map<string, string>>()
  for (const row of rows) {
    const modifiers = row.emoji.match(toneModifierPattern)
    if (!modifiers) continue
    const first = modifiers[0]
    if (!modifiers.every((modifier) => modifier === first)) continue
    const key = usageKey(row.emoji)
    let byTone = variants.get(key)
    if (!byTone) variants.set(key, (byTone = new Map()))
    byTone.set(first, row.emoji)
  }

  const base = rows.filter((row) => !containsSkinTone(row.emoji))
  const shortcodes = new Set<string>()
  let toneable = 0
  let explicitTones = 0
  const lines: string[] = []

  for (const row of base) {
    if (shortcodes.has(row.shortcode)) throw new Error(`duplicate base shortcode: ${row.shortcode}`)
    shortcodes.add(row.shortcode)

    // Terms in the Mac's order (shortcode, aliases, keywords); a repeat of an earlier term is dropped, as `makeTerms` does.
    const seen = new Set<string>()
    const shortcodeTerm = normalize(row.shortcode)
    if (shortcodeTerm === "") throw new Error(`empty shortcode for ${row.emoji}`)
    seen.add(shortcodeTerm)
    const keep = (values: readonly string[]) => {
      const out: string[] = []
      for (const value of values) {
        const term = normalize(value)
        if (term === "" || seen.has(term)) continue
        if (normalize(term) !== term) throw new Error(`normalize is not idempotent for "${value}"`)
        seen.add(term)
        out.push(term)
      }
      return out
    }
    const aliasTerms = keep(aliases.get(row.shortcode) ?? [])
    const keywordTerms = keep(row.keywords)
    for (const term of seen) {
      if (!isAscii(term)) throw new Error(`non-ASCII search term "${term}" for ${row.emoji}; the engine compares ASCII terms`)
      if (term.includes(",")) throw new Error(`comma in term "${term}"`)
    }

    let tone = ""
    const byTone = variants.get(usageKey(row.emoji))
    if (byTone) {
      const light = byTone.get(LIGHT)
      const complete = SKIN_TONES.every((name) => name === "standard" || byTone.has(SKIN_TONE_MODIFIERS[name]))
      if (light && complete) {
        for (const name of SKIN_TONES) {
          if (name === "standard") continue
          const modifier = SKIN_TONE_MODIFIERS[name]
          if (light.replaceAll(LIGHT, modifier) !== byTone.get(modifier)) {
            throw new Error(`tone ${name} of ${row.emoji} is not its light variant with the modifier replaced`)
          }
        }
        tone = insertModifier(row.emoji, LIGHT) === light ? "1" : light
        toneable += 1
        if (tone !== "1") explicitTones += 1
      }
    }

    for (const field of [row.emoji, row.shortcode, row.label]) {
      if (field.includes("\t") || field.includes("\n")) throw new Error(`separator inside a field of ${row.emoji}`)
    }
    lines.push([row.emoji, row.shortcode, row.label, aliasTerms.join(","), keywordTerms.join(","), tone].join("\t"))
  }

  // Sections: the Mac's boundaries by first shortcode, in order (`EmojiPickerData.sectionStarts`).
  const sectionLines: string[] = []
  let previous = -1
  for (const boundary of boundaries) {
    const index = base.findIndex((row) => row.shortcode === boundary.firstShortcode)
    if (index < 0) throw new Error(`section ${boundary.id}: no emoji with shortcode ${boundary.firstShortcode}`)
    if (index <= previous) throw new Error(`section ${boundary.id} starts before the previous section`)
    previous = index
    sectionLines.push([boundary.id, boundary.title, String(index)].join("\t"))
  }

  for (const emoji of popularity) if (emoji.includes(" ")) throw new Error("space in a popular emoji")

  const quickTones: Record<string, string> = {}
  for (const emoji of quick) {
    const row = base.find((candidate) => usageKey(candidate.emoji) === usageKey(emoji))
    const index = row ? base.indexOf(row) : -1
    const tone = index >= 0 ? (lines[index]?.split("\t")[5] ?? "") : ""
    if (tone !== "") quickTones[emoji] = tone
  }

  const data =
    header([SWIFT_SOURCES.data, SWIFT_SOURCES.aliases, SWIFT_SOURCES.pickerData]) +
    [
      "",
      "/**",
      " * One row per base emoji, in Unicode order, separated by newlines. Fields, separated by tabs:",
      " * emoji, shortcode, label, aliases (normalized, comma-separated), CLDR keywords (same), tone",
      ' * (`""` none, `"1"` after the first code point, or the light-tone sequence).',
      " */",
      `export const EMOJI_ROWS = ${JSON.stringify(lines.join("\n"))}`,
      "",
      "/** Picker sections in the standard order: id, title, index of the first row; one per line. */",
      `export const EMOJI_SECTIONS = ${JSON.stringify(sectionLines.join("\n"))}`,
      "",
      "/** How often each emoji is used in chat, most first, separated by spaces (`EmojiAutocompletePopularity.ranked`). */",
      `export const EMOJI_POPULAR = ${JSON.stringify(popularity.join(" "))}`,
      "",
    ].join("\n")

  const quickModule =
    header([SWIFT_SOURCES.reactions, SWIFT_SOURCES.data]) +
    [
      "",
      "/** The quick reaction set, in order (`ReactionPickerEmojis.defaultEmojis`). */",
      `export const QUICK_REACTIONS: readonly string[] = ${JSON.stringify(quick)}`,
      "",
      "/** Tone templates of the quick reactions that take a skin tone (see `tone.ts`). */",
      `export const QUICK_REACTION_TONES: Readonly<Record<string, string>> = ${JSON.stringify(quickTones)}`,
      "",
      "/** Old acknowledgement marks, never offered as quick reactions (`legacyAcknowledgementEmojis`). */",
      `export const LEGACY_ACKNOWLEDGEMENTS: readonly string[] = ${JSON.stringify(legacy)}`,
      "",
    ].join("\n")

  return { data, quick: quickModule, stats: { rows: rows.length, baseRows: base.length, toneable, explicitTones } }
}

/** Whether the files on disk match what the sources generate. */
export const checkEmojiModules = (generated: GeneratedModules = generateEmojiModules()): { data: boolean; quick: boolean } => {
  const read = (file: string) => {
    try {
      return readFileSync(file, "utf8")
    } catch {
      return undefined
    }
  }
  return { data: read(DATA_FILE) === generated.data, quick: read(QUICK_FILE) === generated.quick }
}

const isMain = (() => {
  try {
    return process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]
  } catch {
    return false
  }
})()

if (isMain) {
  const generated = generateEmojiModules()
  if (process.argv.includes("--check")) {
    const result = checkEmojiModules(generated)
    if (!result.data || !result.quick) {
      process.stderr.write("emoji data is out of date: run `bun tooling/emoji/generate.ts` from web/\n")
      process.exit(1)
    }
    process.stdout.write("emoji data is up to date\n")
  } else {
    writeFileSync(DATA_FILE, generated.data)
    writeFileSync(QUICK_FILE, generated.quick)
    const { rows, baseRows, toneable, explicitTones } = generated.stats
    process.stdout.write(`${rows} rows, ${baseRows} base emoji, ${toneable} take a skin tone (${explicitTones} with an explicit template)\n`)
  }
}
